test('a recovery link stores the vault key without leaving the key in the address bar, and local clearing removes it',async({page})=>{
 const key='Q'.repeat(43);
 await page.goto(`/vault/#recover=${key}`);
 await expect(page.locator('#recovery-status')).toContainText('Vault key saved');
 expect(new URL(page.url()).hash).toBe('');
 expect(await page.evaluate(()=>localStorage.getItem('claimclock:vault-key:v1'))).toBe(key);
 await expect(page.locator('#recovery-panel')).toBeVisible();
 await page.locator('#recovery-panel > summary').click();
 await expect(page.locator('#recovery-key')).toHaveValue(key);
 await expect(page.locator('#recovery-key')).toHaveAttribute('type','password');
 await page.click('#recovery-show');await expect(page.locator('#recovery-key')).toHaveAttribute('type','text');
 page.once('dialog',d=>d.accept());await page.click('#vault-clear');
 await expect(page.locator('#vault-status')).toContainText('cleared');
 expect(await page.evaluate(()=>localStorage.getItem('claimclock:vault-key:v1'))).toBeNull();
 // A hash-only change does not reload the page, so leave and come back through a malformed link.
 await page.goto('/about/');await page.goto('/vault/#recover=not-a-key');
 await expect(page.locator('#recovery-status')).toContainText('not a valid recovery key');
});
