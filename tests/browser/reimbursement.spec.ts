const iso=(d:Date)=>d.toISOString().slice(0,10);
const todayUtc=()=>new Date(Date.UTC(new Date().getUTCFullYear(),new Date().getUTCMonth(),new Date().getUTCDate()));
const plusDays=(n:number)=>iso(new Date(todayUtc().getTime()+n*86400000));
const readDownload=async(page:Page,trigger:()=>Promise<void>)=>{const waiting=page.waitForEvent('download');await trigger();const artifact=await waiting;const stream=await artifact.createReadStream(),chunks:Buffer[]=[];for await(const chunk of stream!)chunks.push(chunk);return {name:artifact.suggestedFilename(),text:Buffer.concat(chunks).toString()};};
const closeLetter=async(page:Page)=>{await page.click('#letter-close');await expect(page.locator('#letter-dialog')).toBeHidden();};

