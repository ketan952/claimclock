import {test,expect} from '@playwright/test';

test('coverage simulator reads a catalogue plan, answers check-up, room, waiting and pre/post questions with sources, and sends nothing',async({page})=>{
 const requests:string[]=[];page.on('request',r=>{if(r.method()!=='GET'||!new URL(r.url()).hostname.match(/^(127\.0\.0\.1|localhost|claimclock\.ketan952\.workers\.dev)$/))requests.push(`${r.method()} ${r.url()}`);});
 await page.goto('/check-coverage/');
 await expect(page.locator('h1')).toContainText('Is this covered?');
 await expect(page.locator('#vault-policy-field')).toBeHidden();
 await expect(page.locator('#checkup-result')).toContainText('not verified');
 await page.selectOption('#source-form [name=planId]','niva-bupa-reassure-2');
 await expect(page.locator('#plan-rules')).toContainText('ReAssure 2.0');
 await expect(page.locator('#waiting-form [name=pedMonths]')).toHaveValue('36');
 await expect(page.locator('#prepost-form [name=preDays]')).toHaveValue('60');
 await expect(page.locator('#prepost-form [name=postDays]')).toHaveValue('180');
 await page.fill('#source-form [name=sumInsured]','1000000');
 await page.fill('#source-form [name=inceptionDate]','2026-10-01');
 await expect(page.locator('#checkup-result .verdict')).toContainText('available this policy year');
 await expect(page.locator('#checkup-result .amount')).toHaveText('₹5,000');
 await expect(page.locator('#checkup-result')).toContainText('Cashless only');
 // ₹500 per lakh: at ₹10 lakh the raw figure already equals the individual cap, so the floater cap only shows at a higher sum insured.
 await page.check('#source-form [name=floater]');
 await expect(page.locator('#checkup-result .amount')).toHaveText('₹5,000');
 await page.fill('#source-form [name=sumInsured]','2500000');
 await expect(page.locator('#checkup-result .amount')).toHaveText('₹10,000');
 await page.uncheck('#source-form [name=floater]');
 await expect(page.locator('#checkup-result .amount')).toHaveText('₹5,000');
 await page.fill('#source-form [name=sumInsured]','1000000');
 await page.fill('#checkup-form [name=lastClaimedOn]','2026-10-10');
 await expect(page.locator('#checkup-result .verdict')).toContainText('Already used');
 await expect(page.locator('#checkup-result')).toContainText('Next eligible from 1 October 2027');
 await page.fill('#checkup-form [name=lastClaimedOn]','');
 // Room: a no-cap plan needs no hospital rate; a category plan does.
 await expect(page.locator('#room-eligible-field')).toBeHidden();
 await page.fill('#room-form [name=chosenRoomRent]','9000');await page.fill('#room-form [name=associatedExpenses]','100000');
 await page.click('#room-form button[type=submit]');
 await expect(page.locator('#room-result .verdict')).toContainText('No room-rent limit');
 await page.selectOption('#source-form [name=planId]','star-comprehensive');
 await expect(page.locator('#room-eligible-field')).toBeVisible();
 await page.click('#room-form button[type=submit]');
 await expect(page.locator('#room-result .verdict')).toContainText('hospital’s rate');
 await page.fill('#room-form [name=hospitalEligibleRate]','6000');await page.click('#room-form button[type=submit]');
 await expect(page.locator('#room-result .verdict')).toContainText('Expected out-of-pocket impact');
 await expect(page.locator('#room-result .amount')).toHaveText('₹42,333');
 await expect(page.locator('#room-result')).toContainText('Eligible room rent: ₹6,000 per day');
 await expect(page.locator('#room-result')).toContainText('(33%)');
 await page.fill('#room-form [name=days]','0');await page.click('#room-form button[type=submit]');
 await expect(page.locator('#room-result .verdict')).toContainText('Check the numbers');
 await page.fill('#room-form [name=days]','3');
 // Manual override: a percent rule needs the sum insured and reads it from the policy card.
 await page.selectOption('#room-form [name=roomRule]','percent');await page.fill('#room-form [name=roomPercent]','1');await page.click('#room-form button[type=submit]');
 await expect(page.locator('#room-result')).toContainText('Eligible room rent: ₹10,000 per day');
 await expect(page.locator('#room-result .verdict')).toContainText('Within your eligible room');
 // Waiting periods from the continuity date; Star Comprehensive's claim-free check-up condition appears.
 await page.fill('#source-form [name=continuityFrom]','2021-05-12');
 await expect(page.locator('#waiting-result .verdict')).toContainText('months of continuous cover since 12 May 2021');
 await expect(page.locator('#waiting-result')).toContainText('60-month moratorium (Health MC Ch. I 13): completed on 12 May 2026');
 await expect(page.locator('#claim-free-field')).toBeVisible();
 await expect(page.locator('#checkup-result .verdict')).toContainText('Not in the first policy year');
 await page.fill('#source-form [name=inceptionDate]','2025-10-01');
 await expect(page.locator('#checkup-result .verdict')).toContainText('after a claim-free year');
 await page.selectOption('#checkup-form [name=claimFree]','no');
 await expect(page.locator('#checkup-result .verdict')).toContainText('last policy year had a claim');
 await page.selectOption('#checkup-form [name=claimFree]','yes');
 await expect(page.locator('#checkup-result .amount')).toHaveText('₹3,000');
 await page.fill('#source-form [name=continuityFrom]','2027-01-01');
 await expect(page.locator('#waiting-result .verdict')).toContainText('cannot start after the current policy');
 await page.fill('#source-form [name=continuityFrom]','');
 // Pre/post window with boundary dates.
 await page.fill('#prepost-form [name=admissionDate]','2026-06-10');await page.fill('#prepost-form [name=dischargeDate]','2026-06-14');await page.fill('#prepost-form [name=expenseDate]','2026-04-11');
 await page.click('#prepost-form button[type=submit]');
 await expect(page.locator('#prepost-result .verdict')).toContainText('Inside the pre-hospitalisation window');
 await page.fill('#prepost-form [name=expenseDate]','2026-09-13');await page.click('#prepost-form button[type=submit]');
 await expect(page.locator('#prepost-result .verdict')).toContainText('Too late');
 await page.fill('#prepost-form [name=dischargeDate]','2026-06-01');await page.click('#prepost-form button[type=submit]');
 await expect(page.locator('#prepost-result .verdict')).toContainText('discharge cannot be before admission');
 // Co-pay depends on entry age for this plan.
 await page.fill('#copay-form [name=admissible]','200000');
 await expect(page.locator('#copay-result')).toContainText('depends on the age at entry');
 await page.fill('#source-form [name=entryAge]','62');
 await expect(page.locator('#copay-result .verdict')).toContainText('Co-payment: 10%');
 await expect(page.locator('#copay-result .amount')).toHaveText('₹20,000');
 await expect(page.locator('#coverage-sources a[href^="https://"]').first()).toBeVisible();
 await page.click('[data-language=hi]');
 await expect(page.locator('h1')).toContainText('क्या यह कवर है?');
 await expect(page.locator('#copay-result .verdict')).toContainText('सह-भुगतान: 10%');
 await page.setViewportSize({width:360,height:800});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 expect(requests).toEqual([]);
});
