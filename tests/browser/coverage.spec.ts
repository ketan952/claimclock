test('plan comparison fills a sourced table for up to three plans, survives a shared URL and gives structural family advice',async({page})=>{
 await page.goto('/compare/');
 await expect(page.locator('#compare-table')).toBeHidden();
 await expect(page.locator('#compare-status')).toContainText('Choose at least one plan');
 await page.selectOption('#compare-form [name=plan1]','hdfc-ergo-optima-secure');
 await page.selectOption('#compare-form [name=plan2]','new-india-mediclaim');
 await page.selectOption('#compare-form [name=plan3]','star-senior-citizens-red-carpet');
 await expect(page.locator('#compare-table')).toBeVisible();
 await expect(page.locator('#compare-head th')).toHaveCount(4);
 const row=(key:string)=>page.locator(`#compare-body tr[data-row="${key}"] td`);
 for(const [i,expected] of ['36 months','36 months','12 months'].entries())await expect(row('ped_waiting_months').nth(i)).toContainText(expected);
 await expect(row('room_rent').nth(1)).toContainText('1% of sum insured per day');
 await expect(row('consumables').nth(1)).toHaveClass(/unknown/);
 await expect(row('consumables').nth(1)).toContainText('not verified');
 await expect(row('pre_post_hospitalisation').nth(2)).toContainText('7%');
 await expect(row('copay').nth(2)).toContainText('30%');
 await expect(page.locator('#compare-body a[href^="https://"]').first()).toBeVisible();
 await expect(row('discharge_lt1h').first()).toContainText(/%|No numeric disclosure/);
 expect(new URL(page.url()).searchParams.get('plans')).toBe('hdfc-ergo-optima-secure,new-india-mediclaim,star-senior-citizens-red-carpet');
 await page.goto('/compare/?plans=care-supreme,invented-plan,icici-lombard-elevate,care-supreme');
 await expect(page.locator('#compare-head th')).toHaveCount(3);
 await expect(page.locator('#compare-head th').nth(1)).toContainText('Care Supreme');
 await expect(page.locator('#compare-head th').nth(2)).toContainText('Elevate');
 // Family advisor: default family, then a senior with a condition joins.
 await expect(page.locator('#family-members .member-row')).toHaveCount(3);
 await expect(page.locator('#family-advice li').first()).toContainText('Everyone is under 60');
 await page.click('#family-add');
 await page.locator('#family-members .member-row').nth(3).locator('input[type=number]').fill('67');
 await page.locator('#family-members .member-row').nth(3).locator('input[type=checkbox]').check();
 await expect(page.locator('#family-advice')).toContainText('1 member(s) are 60 or older');
 await expect(page.locator('#family-advice')).toContainText('declare every condition');
 await expect(page.locator('#family-advice')).toContainText('super top-up');
 await expect(page.locator('#family-advice li.final')).toContainText('not a recommendation');
 await page.locator('#family-members .member-row').nth(3).locator('input[type=number]').fill('130');
 await expect(page.locator('#family-advice')).toContainText('between 0 and 120');
 await page.locator('#family-members .member-row').nth(3).locator('input[type=number]').fill('');
 await expect(page.locator('#family-advice')).toContainText('Enter an age for every member');
 // Four rows exist; eight more reach the twelve-member limit and the button disables itself.
 for(let i=0;i<8;i++)await page.click('#family-add');
 await expect(page.locator('#family-members .member-row')).toHaveCount(12);
 await expect(page.locator('#family-add')).toBeDisabled();
 await page.click('#family-clear');
 await expect(page.locator('#family-members .member-row')).toHaveCount(0);
 await expect(page.locator('#family-advice')).toBeEmpty();
 await page.click('[data-language=hi]');
 await expect(page.locator('h1')).toContainText('योजनाओं की तुलना');
 await expect(row('ped_waiting_months').first()).toContainText('36 माह');
 await page.setViewportSize({width:360,height:800});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
});
