import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';

test('desktop clock, separate phone links and printable evidence export',async({page})=>{
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('/');
 await mkdir('qa/screenshots',{recursive:true});
 await page.screenshot({path:'qa/screenshots/desktop-home.png',fullPage:true});
 await page.selectOption('[name=insurer]','care');
 await page.fill('[name=hospital]','Example Hospital');
 await page.fill('[name=city]','Pune');
 const past=new Date(Date.now()-100*60000);
 await page.fill('[name=submittedAt]',new Date(past.getTime()-past.getTimezoneOffset()*60000).toISOString().slice(0,16));
 await page.click('#start-form button[type=submit]');
 await expect(page.locator('#clock-next')).toContainText('follow-up');
 await expect(page.locator('#contacts a[href="tel:18001024488"]')).toHaveCount(1);
 await expect(page.locator('#contacts a[href="tel:18001026655"]')).toHaveCount(1);
 await page.fill('#event-form [name=note]','Written acknowledgement: TEST-001');
 await page.click('#event-form button');
 const downloadPromise=page.waitForEvent('download');
 await page.click('#export-timeline');
 const download=await downloadPromise;
 expect(download.suggestedFilename()).toBe('claimclock-timeline.json');
 const stream=await download.createReadStream();
 const chunks:Buffer[]=[];for await(const chunk of stream!)chunks.push(chunk);
 const exported=JSON.parse(Buffer.concat(chunks).toString());
 expect(exported.insurerId).toBe('care');
 expect(exported.events[0].note).toBe('Written acknowledgement: TEST-001');
 await page.evaluate(()=>{window.print=()=>{};});
 await page.click('#print-timeline');
 await page.emulateMedia({media:'print'});
 await expect(page.locator('#print-root')).toBeVisible();
 await expect(page.locator('#print-root')).toContainText('Written acknowledgement: TEST-001');
 await expect(page.locator('#print-root')).toContainText('Example Hospital');
 await expect(page.locator('header')).toBeHidden();
 await mkdir('.cache/qa',{recursive:true});
 await page.pdf({path:'.cache/qa/synthetic-timeline.pdf',format:'A4',printBackground:true});
 await page.screenshot({path:'qa/screenshots/print-timeline.png',fullPage:true});
});
